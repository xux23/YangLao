function isCJK(ch) {
  const c = ch.codePointAt(0);
  return (c >= 0x4E00 && c <= 0x9FFF) || (c >= 0x3400 && c <= 0x4DBF) ||
    (c >= 0x3000 && c <= 0x303F) || (c >= 0xFF00 && c <= 0xFFEF) || (c >= 0x2E80 && c <= 0x2EFF);
}
function textWidth(text, pt) {
  let w = 0;
  for (const ch of text) w += isCJK(ch) ? pt * 20 : pt * 11;
  return w;
}
function splitTitleByWidth(title, maxW, pt) {
  if (textWidth(title, pt) <= maxW) return [title];
  const breakAfter = new Set([...'\uFF0C\u3001\uFF1B\uFF1A\u3002\uFF01\uFF1F', ...'\u7684\u4E0E\u548C\u53CA\u4E4B\u5728\u4E3A\u540E\u524D', ...' \t']);
  const lines = [];
  let remaining = title;
  while (textWidth(remaining, pt) > maxW) {
    let breakAt = -1;
    let w = 0;
    for (let i = 0; i < remaining.length; i++) {
      w += isCJK(remaining[i]) ? pt * 20 : pt * 11;
      if (w >= maxW * 0.9 && breakAfter.has(remaining[i])) { breakAt = i + 1; break; }
    }
    if (breakAt === -1) {
      w = 0;
      for (let i = 0; i < remaining.length; i++) {
        w += isCJK(remaining[i]) ? pt * 20 : pt * 11;
        if (w >= maxW) { breakAt = i; break; }
      }
    }
    if (breakAt <= 0 || breakAt >= remaining.length) breakAt = Math.floor(remaining.length / 2);
    lines.push(remaining.slice(0, breakAt).trim());
    remaining = remaining.slice(breakAt).trim();
  }
  if (remaining) lines.push(remaining);
  if (lines.length > 1 && textWidth(lines[lines.length - 1], pt) <= pt * 40) {
    const last = lines.pop();
    lines[lines.length - 1] += last;
  }
  return lines;
}

