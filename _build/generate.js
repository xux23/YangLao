function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    alignment: AlignmentType.LEFT,
    spacing: { before: 480, after: 240, line: LINE_15 },
    children: [new TextRun({ text, bold: true, size: 32, font: { eastAsia: "SimHei", ascii: "Times New Roman" } })],
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    alignment: AlignmentType.LEFT,
    spacing: { before: 240, after: 120, line: LINE_15 },
    children: [new TextRun({ text, bold: true, size: 28, font: { eastAsia: "SimHei", ascii: "Times New Roman" } })],
  });
}
function bodyPara(text, cites) {
  const runs = [new TextRun({ text, size: 24, font: { eastAsia: "SimSun", ascii: "Times New Roman" } })];
  if (cites) {
    for (const c of cites) {
      runs.push(new TextRun({ text: c, superScript: true, size: 18, font: { ascii: "Times New Roman" } }));
    }
  }
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { firstLine: 480 },
    spacing: { line: LINE_15 },
    children: runs,
  });
}
function caption(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    keepNext: true,
    spacing: { before: 120, after: 60, line: LINE_15 },
    children: [new TextRun({ text, bold: true, size: 21, font: { eastAsia: "SimSun", ascii: "Times New Roman" } })],
  });
}
function cellPara(text, bold) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { line: 312 },
    children: [new TextRun({ text, bold, size: 21, font: { eastAsia: "SimSun", ascii: "Times New Roman" } })],
  });
}
function threeLineTable(headers, rows, colPcts) {
  const mkRow = (cells, isHeader) => new TableRow({
    tableHeader: isHeader,
    cantSplit: true,
    children: cells.map((text, i) => new TableCell({
      width: { size: colPcts[i], type: WidthType.PERCENTAGE },
      borders: isHeader
        ? { top: NB, left: NB, right: NB, bottom: { style: BorderStyle.SINGLE, size: 2, color: "000000" } }
        : noBorders,
      margins: { top: 60, bottom: 60, left: 120, right: 120 },
      children: [cellPara(text, isHeader)],
    })),
  });
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: "000000" },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: "000000" },
      left: { style: BorderStyle.NONE },
      right: { style: BorderStyle.NONE },
      insideHorizontal: { style: BorderStyle.NONE },
      insideVertical: { style: BorderStyle.NONE },
    },
    rows: [mkRow(headers, true), ...rows.map((r) => mkRow(r, false))],
  });
}
function refPara(text) {
  return new Paragraph({
    indent: { left: 420, hanging: 420 },
    spacing: { line: LINE_15 },
    children: [new TextRun({ text, size: 21, font: { eastAsia: "SimSun", ascii: "Times New Roman" } })],
  });
}

